import {sourceMeshData,createSourceAccess} from './body-source-contract.mjs';
// Experimental Three.js adapter for SHA256-verified, bit-exact POLY source chunks.
// No new anatomical geometry, muscle insertions, personalized coordinates or physiology.
export const REGION_COLORS = Object.freeze({
  skeletal:0xe4ddc8, muscular:0xb76c69, nervous:0xdfbc83,
  circulatory:0xe66f7b, respiratory:0x78c9d5, digestive:0xe3ad73,
  urinary:0xc799d8, integumentary:0xb7b5ac, lymphatic:0x81c897,
  male_reproductive:0xd08bc8
});

const ensure = (v, message) => {if(!v) throw Error(message)};
const failSafeDispose = resource => resource?.dispose?.();

function typedData(bytes, offset, n, Type) {
  const start = bytes.byteOffset + offset;
  ensure(Number.isInteger(offset) && offset>=0 && offset%4===0 &&
    Number.isSafeInteger(n) && n>=0 && start+n*4<=bytes.byteOffset+bytes.byteLength,
    'Invalid geometry offset');
  ensure(start % Type.BYTES_PER_ELEMENT===0,'Unaligned atlas source buffer');
  return new Type(bytes.buffer,start,n);
}

export function createRegionSceneAdapter({THREE, scene, onChange=()=>{}, onSelectionLost=()=>{}, rig=null}) {
  ensure(THREE?.BufferGeometry && THREE?.BufferAttribute && THREE?.Mesh && THREE?.Group,
    'Three.js geometric primitives missing');
  ensure(scene?.add && scene?.remove, 'Three.js scene missing');
  const installed=new Map();
  const sourceMeshes=new Map();
  let selectedIndex=null;
  let selectedMesh=null;

  function unhighlight() {
    if(selectedMesh?.material?.emissive) selectedMesh.material.emissive.setHex(0);
    selectedMesh=null;
    selectedIndex=null;
  }

  function removeState(state) {
    if(!state || state.disposed) return false;
    state.disposed=true;
    if(state.meshes.some(m=>m===selectedMesh)){
      unhighlight();
      onSelectionLost();
    }
    scene.remove(state.group);
    for(const mesh of state.meshes){
      if(sourceMeshes.get(mesh.userData.source_index)===mesh)
        sourceMeshes.delete(mesh.userData.source_index);
      state.group.remove(mesh);
      failSafeDispose(mesh.geometry);
      failSafeDispose(mesh.material);
    }
    state.meshes.length=0;
    installed.delete(state.id);
    onChange();
    return true;
  }

  // Install occurs only after the reader has validated both metadata and geometry SHA256.
  function install(chunk) {
    ensure(chunk?.metadata?.schema==='poly.body-source-chunk-metadata.v1' &&
      chunk.metadata.coordinate_policy==='byte_exact_no_transform', 'Not a source-faithful chunk');
    ensure(chunk.bytes instanceof Uint8Array, 'Missing byte-verified geometry');
    ensure(!installed.has(chunk.id), 'Chunk already installed');
    const group=new THREE.Group();
    group.name='POLY source block '+chunk.id;
    const state={id:chunk.id,system:chunk.system,group,meshes:[],disposed:false,
      triangles:0,vertices:0};
    // Buffers generated by Node's zlib can have unaligned offsets; copy only in that case.
    const aligned=(chunk.bytes.byteOffset%4===0)?chunk.bytes:new Uint8Array(chunk.bytes);
    try {
      for(const record of chunk.metadata.geometries){
        ensure(!sourceMeshes.has(record.source_index),'Duplicate source structure across resident blocks');
        let geometry=null, material=null;
        try {
          geometry=new THREE.BufferGeometry();
          geometry.setAttribute('position',new THREE.BufferAttribute(
            typedData(aligned,record.position_offset,record.vertex_count*3,Float32Array),3));
          geometry.setAttribute('normal',new THREE.BufferAttribute(
            typedData(aligned,record.normal_offset,record.vertex_count*3,Float32Array),3));
          geometry.setIndex(new THREE.BufferAttribute(
            typedData(aligned,record.index_offset,record.triangle_count*3,Uint32Array),1));
          geometry.computeBoundingSphere();
          const integument=chunk.system==='integumentary';
          material=new THREE.MeshStandardMaterial({
            color:REGION_COLORS[chunk.system]??0x9eb9c6,roughness:.65,metalness:.04,
            side:THREE.DoubleSide,transparent:integument,
            opacity:integument?.18:1,depthWrite:!integument
          });
          rig?.bind(material);
          const mesh=new THREE.Mesh(geometry,material);
          mesh.name=record.name;
          mesh.userData={...sourceMeshData(record,{system:chunk.system,chunkId:chunk.id}),source_name:record.name,
            source_node:record.node??null,source_path:[...record.path],
            source_offsets:{...record.source_offsets},
            bounds:record.bounds,system:chunk.system,chunk_id:chunk.id,
            triangle_count:record.triangle_count,vertex_count:record.vertex_count,
            provenance:'byte_exact_SOURCE_BIN_sha256'};
          mesh.frustumCulled=!rig;
          group.add(mesh);
          state.meshes.push(mesh);
          state.triangles+=record.triangle_count;
          state.vertices+=record.vertex_count;
        } catch(error) {
          failSafeDispose(geometry);
          failSafeDispose(material);
          throw error;
        }
      }
      scene.add(group);
      installed.set(chunk.id,state);
      for(const mesh of state.meshes) sourceMeshes.set(mesh.userData.source_index,mesh);
      onChange();
      return state;
    } catch(error) {
      // Atomic failure also removes registry entries if a consumer callback failed.
      installed.delete(chunk.id);
      for(const mesh of state.meshes)if(sourceMeshes.get(mesh.userData.source_index)===mesh)sourceMeshes.delete(mesh.userData.source_index);
      scene.remove(group);
      for(const mesh of state.meshes){
        group.remove(mesh);
        failSafeDispose(mesh.geometry);
        failSafeDispose(mesh.material);
      }
      throw error;
    }
  }

  function uninstall(installedToken,chunk) {
    const state=installed.get(chunk?.id??installedToken?.id);
    if(installedToken&&state!==installedToken)return false;
    return removeState(state);
  }

  function select(sourceIndex) {
    ensure(Number.isInteger(sourceIndex),'Invalid original structure index');
    const mesh=sourceMeshes.get(sourceIndex);
    if(!mesh)return null;
    unhighlight();
    selectedMesh=mesh;selectedIndex=sourceIndex;
    mesh.material.emissive.setHex(0x273d38);
    onChange();
    return {
      source_index:sourceIndex,name:mesh.userData.source_name,
      path:[...mesh.userData.source_path],node:mesh.userData.source_node,
      source_offsets:{...mesh.userData.source_offsets},bounds:mesh.userData.bounds,
      chunk_id:mesh.userData.chunk_id,system:mesh.userData.system,
      vertex_count:mesh.userData.vertex_count,triangle_count:mesh.userData.triangle_count
    };
  }
  function pick(raycaster){
    const meshes=[...sourceMeshes.values()].filter(m=>m.visible!==false);
    if(!meshes.length)return null;
    let hits=[];
    if(!rig)hits=raycaster.intersectObjects(meshes,false);
    else{
      // One workspace per pick, bounded by the largest resident surface. No retained proxy.
      const geometry=new THREE.BufferGeometry();
      try{
       const workspace=new Float32Array(Math.max(...meshes.map(m=>m.geometry.attributes.position.array.length)));
       const proxy=new THREE.Mesh(geometry,meshes[0].material);
       for(const mesh of meshes){
        const source=mesh.geometry.attributes.position.array,points=new Float32Array(workspace.buffer,0,source.length);
        for(let i=0;i<source.length;i+=3)points.set(rig.deform([source[i],source[i+1],source[i+2]]),i);
        geometry.setAttribute('position',new THREE.BufferAttribute(points,3));
        geometry.setIndex(mesh.geometry.index);
        geometry.boundingSphere=null;geometry.boundingBox=null;proxy.material=mesh.material;
        for(const hit of raycaster.intersectObject(proxy,false))hits.push({...hit,object:mesh});
       }
      }finally{geometry.dispose()}
    }
    hits.sort((a,b)=>a.distance-b.distance);
    return hits.length?select(hits[0].object.userData.source_index):null;
  }

  function diagnostics(){
    const blocks=[...installed.values()];
    return {blocks:blocks.map(b=>b.id),meshes:sourceMeshes.size,
      triangles:blocks.reduce((s,b)=>s+b.triangles,0),
      vertices:blocks.reduce((s,b)=>s+b.vertices,0),
      selected_source_index:selectedIndex,source_identifiers_preserved:true};
  }
  function dispose(){
    for(const state of [...installed.values()]) removeState(state);
    unhighlight();
  }
  return {install,uninstall,select,pick,dispose,diagnostics,
    sources:createSourceAccess(()=>[...sourceMeshes.values()]),
    sourceInfo:index=>{const m=sourceMeshes.get(index);return m?{name:m.userData.source_name,source_index:index,chunk_id:m.userData.chunk_id,bounds:m.userData.bounds}:null},
    listSourceIndices:()=>[...sourceMeshes.keys()].sort((a,b)=>a-b)};
}
